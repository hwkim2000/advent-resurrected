/*
 * Skip_List for the Fidelity_Suite (requirements 15.6, 15.11).
 *
 * Exactly 4 upstream logs are skipped. They depend on binary `.adv` save
 * fixtures that cannot be reproduced through the JSON Save_Document format:
 * either produced by the upstream `cheat` tool, or a C binary save with no
 * generating rule.
 *
 * NOT skipped (keep active):
 *  - `resumefail`: loads no fixture; it exercises only the failed-open path
 *    through the injected storage interface.
 *  - `badmagic`: replayed with a static garbage fixture serving `../main.o`.
 *  - `savefail`, `saveresume.1` to `saveresume.4`: fixtures are produced by
 *    earlier logs through the harness MemoryStorage.
 *
 * Copyright (c) Open Adventure authors; BSD-2-Clause. See original/COPYING.
 */

export interface SkipEntry {
  /** Base filename of the log, without the `.log` extension. */
  readonly name: string;
  /** One-line reason the log is skipped. */
  readonly reason: string;
}

export const SKIP_LIST: readonly SkipEntry[] = [
  {
    name: 'savetamper',
    reason: 'Needs a tampered .adv fixture generated by the upstream cheat tool.',
  },
  {
    name: 'cheatresume',
    reason: 'Needs a .adv fixture generated by the upstream cheat tool.',
  },
  {
    name: 'cheatresume2',
    reason: 'Needs a .adv fixture generated by the upstream cheat tool.',
  },
  {
    name: 'resumefail2',
    reason: 'Needs the C binary save resume_badversion.adv, which has no generating rule.',
  },
] as const;

/** Set of skipped base names, for quick lookup. */
export const SKIP_NAMES: ReadonlySet<string> = new Set(SKIP_LIST.map((e) => e.name));
